package com.educenter.service.impl;

import com.educenter.entity.ClassEntity;
import com.educenter.entity.Student;
import com.educenter.entity.Tuition;
import com.educenter.repository.TuitionRepository;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.mockito.ArgumentCaptor;
import org.mockito.Mock;
import org.mockito.junit.jupiter.MockitoExtension;

import java.math.BigDecimal;
import java.time.LocalDate;
import java.time.YearMonth;
import java.util.List;

import static org.junit.jupiter.api.Assertions.*;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.Mockito.*;

@ExtendWith(MockitoExtension.class)
class MonthlyTuitionBillingServiceTest {

    @Mock
    private TuitionRepository tuitionRepository;

    private MonthlyTuitionBillingService billingService;
    private Student student;
    private ClassEntity classEntity;

    @BeforeEach
    void setUp() {
        billingService = new MonthlyTuitionBillingService(tuitionRepository);
        student = new Student();
        student.setId(7L);
        classEntity = new ClassEntity();
        classEntity.setId(3L);
        classEntity.setName("Toán 10");
        classEntity.setSessionFee(new BigDecimal("150000"));
        when(tuitionRepository.findByStudentIdAndClassEntityIdAndBillingPeriodIsNull(7L, 3L)).thenReturn(List.of());
    }

    @Test
    void createsInvoiceForPresentSessionTotal() {
        when(tuitionRepository.findByStudentIdAndClassEntityIdAndBillingPeriodOrderByBillingSequenceAsc(
                7L, 3L, LocalDate.of(2026, 11, 1))).thenReturn(List.of());

        billingService.synchronizeCharge(student, classEntity, YearMonth.of(2026, 11), new BigDecimal("300000"));

        ArgumentCaptor<Tuition> captor = ArgumentCaptor.forClass(Tuition.class);
        verify(tuitionRepository).save(captor.capture());
        Tuition invoice = captor.getValue();
        assertEquals(new BigDecimal("300000"), invoice.getAmount());
        assertEquals(LocalDate.of(2026, 11, 1), invoice.getBillingPeriod());
        assertEquals(1, invoice.getBillingSequence());
        assertTrue(invoice.isAutoGenerated());
        assertEquals("UNPAID", invoice.getStatus());
    }

    @Test
    void updatesExistingUnpaidInvoiceInsteadOfCreatingDuplicate() {
        Tuition unpaid = new Tuition();
        unpaid.setId(10L);
        unpaid.setAmount(new BigDecimal("150000"));
        unpaid.setStatus("UNPAID");
        when(tuitionRepository.findByStudentIdAndClassEntityIdAndBillingPeriodOrderByBillingSequenceAsc(
                7L, 3L, LocalDate.of(2026, 11, 1))).thenReturn(List.of(unpaid));

        billingService.synchronizeCharge(student, classEntity, YearMonth.of(2026, 11), new BigDecimal("450000"));

        assertEquals(new BigDecimal("450000"), unpaid.getAmount());
        assertTrue(unpaid.isAutoGenerated());
        assertEquals(LocalDate.of(2026, 11, 1), unpaid.getBillingPeriod());
        verify(tuitionRepository, never()).save(argThat(t -> t.getId() == null));
    }

    @Test
    void createsSupplementForAmountAboveAlreadyPaidTuition() {
        Tuition paid = new Tuition();
        paid.setId(11L);
        paid.setAmount(new BigDecimal("300000"));
        paid.setStatus("PAID");
        when(tuitionRepository.findByStudentIdAndClassEntityIdAndBillingPeriodOrderByBillingSequenceAsc(
                7L, 3L, LocalDate.of(2026, 11, 1))).thenReturn(List.of(paid));

        billingService.synchronizeCharge(student, classEntity, YearMonth.of(2026, 11), new BigDecimal("450000"));

        ArgumentCaptor<Tuition> captor = ArgumentCaptor.forClass(Tuition.class);
        verify(tuitionRepository).save(captor.capture());
        Tuition supplement = captor.getValue();
        assertEquals(new BigDecimal("150000"), supplement.getAmount());
        assertEquals(1, supplement.getBillingSequence());
        assertEquals("UNPAID", supplement.getStatus());
    }

    @Test
    void createsNoInvoiceWhenNothingIsOwed() {
        when(tuitionRepository.findByStudentIdAndClassEntityIdAndBillingPeriodOrderByBillingSequenceAsc(
                7L, 3L, LocalDate.of(2026, 11, 1))).thenReturn(List.of());

        billingService.synchronizeCharge(student, classEntity, YearMonth.of(2026, 11), BigDecimal.ZERO);

        verify(tuitionRepository, never()).save(any(Tuition.class));
    }
}
