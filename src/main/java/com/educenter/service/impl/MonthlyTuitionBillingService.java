package com.educenter.service.impl;

import com.educenter.entity.ClassEntity;
import com.educenter.entity.Student;
import com.educenter.entity.Tuition;
import com.educenter.repository.TuitionRepository;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import java.math.BigDecimal;
import java.time.LocalDate;
import java.time.YearMonth;
import java.time.ZoneId;
import java.util.Comparator;
import java.util.List;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

@Service
public class MonthlyTuitionBillingService {

    private static final ZoneId APP_ZONE = ZoneId.of("Asia/Ho_Chi_Minh");
    private static final Pattern MONTH_AND_YEAR = Pattern.compile("(?i)tháng\\s*(\\d{1,2})\\s*[/.-]\\s*(\\d{4})");
    private static final Pattern MONTH_ONLY = Pattern.compile("(?i)tháng\\s*(\\d{1,2})");

    private final TuitionRepository tuitionRepository;

    public MonthlyTuitionBillingService(TuitionRepository tuitionRepository) {
        this.tuitionRepository = tuitionRepository;
    }

    @Transactional
    public boolean synchronizeCharge(Student student, ClassEntity classEntity, YearMonth month, BigDecimal calculatedTotal) {
        if (classEntity.getSessionFee() == null) return false;

        LocalDate period = month.atDay(1);
        resolveLegacyPeriods(student.getId(), classEntity.getId(), month);

        List<Tuition> periodTuitions = tuitionRepository.findByStudentIdAndClassEntityIdAndBillingPeriodOrderByBillingSequenceAsc(
                student.getId(), classEntity.getId(), period);
        List<Tuition> unresolvedLegacy = tuitionRepository.findByStudentIdAndClassEntityIdAndBillingPeriodIsNull(student.getId(), classEntity.getId())
                .stream().filter(t -> !t.isAutoGenerated()).toList();
        if (!unresolvedLegacy.isEmpty()) {
            return false;
        }

        BigDecimal paidTotal = periodTuitions.stream()
                .filter(t -> "PAID".equals(t.getStatus()))
                .map(Tuition::getAmount)
                .reduce(BigDecimal.ZERO, BigDecimal::add);
        BigDecimal outstanding = calculatedTotal.subtract(paidTotal).max(BigDecimal.ZERO);

        List<Tuition> unpaid = periodTuitions.stream()
                .filter(t -> "UNPAID".equals(t.getStatus()))
                .sorted(Comparator.comparing(Tuition::isAutoGenerated).reversed().thenComparing(Tuition::getId))
                .toList();

        if (outstanding.signum() == 0) {
            unpaid.forEach(t -> t.setStatus("CANCELLED"));
            tuitionRepository.saveAll(unpaid);
            return true;
        }

        if (!unpaid.isEmpty()) {
            Tuition mainInvoice = unpaid.get(0);
            mainInvoice.setAmount(outstanding);
            mainInvoice.setAutoGenerated(true);
            mainInvoice.setBillingPeriod(period);
            if (mainInvoice.getBillingSequence() == null) mainInvoice.setBillingSequence(nextSequence(periodTuitions));
            mainInvoice.setDescription(description(month, classEntity));
            if (mainInvoice.getDueDate() == null) mainInvoice.setDueDate(LocalDate.now(APP_ZONE).plusDays(15));
            tuitionRepository.save(mainInvoice);
            for (int i = 1; i < unpaid.size(); i++) {
                unpaid.get(i).setStatus("CANCELLED");
            }
            tuitionRepository.saveAll(unpaid.subList(1, unpaid.size()));
            return true;
        }

        Tuition invoice = new Tuition();
        invoice.setStudent(student);
        invoice.setClassEntity(classEntity);
        invoice.setAmount(outstanding);
        invoice.setDueDate(LocalDate.now(APP_ZONE).plusDays(15));
        invoice.setStatus("UNPAID");
        invoice.setBillingPeriod(period);
        invoice.setBillingSequence(nextSequence(periodTuitions));
        invoice.setAutoGenerated(true);
        invoice.setDescription(description(month, classEntity));
        tuitionRepository.save(invoice);
        return true;
    }

    private int nextSequence(List<Tuition> existing) {
        return existing.stream().map(Tuition::getBillingSequence).filter(s -> s != null)
                .max(Integer::compareTo).orElse(0) + 1;
    }

    private String description(YearMonth month, ClassEntity classEntity) {
        return String.format("Học phí tháng %02d/%d - %s (theo số buổi có mặt)", month.getMonthValue(), month.getYear(), classEntity.getName());
    }

    private void resolveLegacyPeriods(Long studentId, Long classId, YearMonth targetMonth) {
        List<Tuition> legacy = tuitionRepository.findByStudentIdAndClassEntityIdAndBillingPeriodIsNull(studentId, classId)
                .stream().filter(t -> !t.isAutoGenerated()).toList();
        for (Tuition tuition : legacy) {
            YearMonth detected = parseMonth(tuition);
            if (detected != null) {
                tuition.setBillingPeriod(detected.atDay(1));
                tuitionRepository.save(tuition);
            }
        }
    }

    private YearMonth parseMonth(Tuition tuition) {
        String description = tuition.getDescription() == null ? "" : tuition.getDescription();
        Matcher monthYear = MONTH_AND_YEAR.matcher(description);
        if (monthYear.find()) {
            try {
                return YearMonth.of(Integer.parseInt(monthYear.group(2)), Integer.parseInt(monthYear.group(1)));
            } catch (RuntimeException ignored) {
                return null;
            }
        }
        Matcher monthOnly = MONTH_ONLY.matcher(description);
        if (monthOnly.find() && tuition.getDueDate() != null) {
            try {
                return YearMonth.of(tuition.getDueDate().getYear(), Integer.parseInt(monthOnly.group(1)));
            } catch (RuntimeException ignored) {
                return null;
            }
        }
        return tuition.getDueDate() == null ? null : YearMonth.from(tuition.getDueDate());
    }
}
